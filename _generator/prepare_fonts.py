#!/usr/bin/env python3
"""Copy the needed woff2 files from fonts_src/node_modules into ../assets/fonts and write ../assets/css/fonts.css.
Also copies the supplied TS Hiba Bold (title font) from source/TSHiba-Bold.otf."""
import re, shutil, os, glob
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
NM=os.path.join(HERE,'fonts_src','node_modules','@fontsource')
OUT=os.path.join(ROOT,'assets','fonts'); os.makedirs(OUT,exist_ok=True)
want={'amiri':[('arabic',400),('arabic',700),('latin',400),('latin',700),('latin-ext',400)],
      'ibm-plex-sans-arabic':[('arabic',400),('arabic',600),('latin',400),('latin',600),('latin-ext',400)],
      'noto-serif':[('latin',400),('latin',700),('latin-ext',400),('latin-ext',700),('vietnamese',400),('vietnamese',700)]}
css=['/* generated by prepare_fonts.py - Amiri, IBM Plex Sans Arabic, Noto Serif (SIL OFL 1.1); TS Hiba Bold supplied by the course author */']
for pkg,subs in want.items():
    for sub,w in subs:
        src=open(os.path.join(NM,pkg,f'{w}.css'),encoding='utf8').read()
        for block in re.findall(r'/\*.*?\*/\s*@font-face\s*\{.*?\}',src,flags=re.S):
            m=re.search(r'/\* (\S+) \*/',block)
            name=m.group(1)
            if f'-{sub}-{w}-normal' not in name: continue
            fam=re.search(r"font-family: '([^']+)'",block).group(1)
            m2=re.search(r'unicode-range: ([^;]+);',block); ur=m2.group(1) if m2 else None
            fn=f'{name}.woff2'
            shutil.copy(os.path.join(NM,pkg,'files',fn),os.path.join(OUT,fn))
            css.append(f"@font-face{{font-family:'{fam}';font-style:normal;font-weight:{w};font-display:swap;src:url(../fonts/{fn}) format('woff2');"+(f'unicode-range:{ur}' if ur else '')+'}')
shutil.copy(os.path.join(HERE,'source','TSHiba-Bold.otf'),os.path.join(OUT,'TSHiba-Bold.otf'))
css.append("@font-face{font-family:'TS Hiba';font-style:normal;font-weight:700;font-display:swap;src:url(../fonts/TSHiba-Bold.otf) format('opentype')}")
open(os.path.join(ROOT,'assets','css','fonts.css'),'w',encoding='utf8').write('\n'.join(css)+'\n')
print('fonts:',len(css)-1,'faces')
